#!/usr/bin/env python3
"""Generate CV research/publication includes from the same data as the Jekyll site.

Requires PyYAML: python3 -m pip install PyYAML
"""
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'media' / 'files'


def tex(value):
    replacements = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$',
                    '#': r'\#', '_': r'\_', '{': r'\{', '}': r'\}', '~': r'\textasciitilde{}',
                    '^': r'\textasciicircum{}', '–': '--', '—': '---'}
    return ''.join(replacements.get(char, char) for char in str(value))


def main():
    profile = yaml.safe_load((ROOT / '_data/profile.yml').read_text())
    papers = yaml.safe_load((ROOT / '_data/publications.yml').read_text())
    (OUTPUT / 'cv_research.tex').write_text('% Generated by scripts/generate-cv.py.\n' + tex(profile['research_intro']) + '\n')
    lines = ['% Generated by scripts/generate-cv.py. Edit _data/publications.yml.']
    for status, label in [('preprint', 'Preprints'), ('published', 'Peer-reviewed publications')]:
        lines.extend([r'\subsection*{' + label + '}', r'\begin{enumerate}[label={\arabic*.},leftmargin=1.4em,itemsep=5pt,parsep=0pt,topsep=3pt]'])
        for paper in (p for p in papers if p['status'] == status):
            authors = ', '.join(r'\textbf{' + tex(name) + '}' if name == 'Dehao Huang' else tex(name) for name in paper['authors'])
            resources = [r'\href{' + paper[key] + '}{' + label + '}' for key, label in [('paper', 'Paper'), ('project', 'Project'), ('code', 'Code')] if key in paper]
            lines.append(r'\item \begin{minipage}[t]{\linewidth}' + authors.rstrip('.') + '. ' + r'\emph{' + tex(paper['title']) + '}. ' + r'\textbf{' + tex(paper['venue']) + ' ' + str(paper['year']) + '}. ' + r'{\small ' + r'\enspace '.join(resources) + r'}\end{minipage}')
        lines.append(r'\end{enumerate}')
    (OUTPUT / 'cv_publications.tex').write_text('\n'.join(lines) + '\n')
    print(f'Generated CV includes for {len(papers)} publications.')


if __name__ == '__main__':
    main()
